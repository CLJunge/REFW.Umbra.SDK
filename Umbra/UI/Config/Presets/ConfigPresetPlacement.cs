namespace Umbra.UI.Config.Presets;

/// <summary>
/// Defines where the built-in preset UI is rendered relative to the main config UI.
/// </summary>
public enum ConfigPresetPlacement
{
    /// <summary>
    /// Renders the preset UI before the main config UI.
    /// </summary>
    BeforeConfig,

    /// <summary>
    /// Renders the preset UI after the main config UI.
    /// </summary>
    AfterConfig
}
